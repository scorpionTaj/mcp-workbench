import path from "node:path";
import { existsSync } from "node:fs";
import { randomUUID } from "node:crypto";

// Uploads live outside public/ so they are only served through the authenticated /uploads route.
// turbopackIgnore: runtime data directories, not build inputs (keeps standalone tracing small).
export const UPLOAD_DIR = process.env.UPLOAD_DIR || path.join(/*turbopackIgnore: true*/ process.cwd(), "storage", "uploads");
// Files from before uploads were private; still readable (by their owner) until moved.
export const LEGACY_UPLOAD_DIR = path.join(/*turbopackIgnore: true*/ process.cwd(), "public", "uploads");

// The stored extension comes from this server-side map, never from the client's
// filename, so nothing a browser would execute (html, svg, js) is served from our origin.
const EXT_BY_MIME: Record<string, string> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/gif": "gif",
  "image/webp": "webp",
  "application/pdf": "pdf",
  "text/plain": "txt",
  "text/markdown": "md",
};

export const ALLOWED_UPLOAD_TYPES = Object.keys(EXT_BY_MIME);

/** Served Content-Type per stored extension (anything else is a download). */
export const MIME_BY_EXT: Record<string, string> = {
  jpg: "image/jpeg",
  png: "image/png",
  gif: "image/gif",
  webp: "image/webp",
  pdf: "application/pdf",
  txt: "text/plain; charset=utf-8",
  md: "text/plain; charset=utf-8",
  csv: "text/csv; charset=utf-8",
  tsv: "text/tab-separated-values; charset=utf-8",
  mp3: "audio/mpeg",
  wav: "audio/wav",
  ogg: "audio/ogg",
  opus: "audio/ogg",
  aac: "audio/aac",
  flac: "audio/flac",
};

// Files the server itself produces (Studio images and speech); the type comes from the provider.
const GENERATED_EXT: Record<string, string> = {
  "image/png": "png",
  "image/jpeg": "jpg",
  "image/webp": "webp",
  "audio/mpeg": "mp3",
  "audio/mp3": "mp3",
  "audio/wav": "wav",
  "audio/x-wav": "wav",
  "audio/ogg": "ogg",
  "audio/opus": "opus",
  "audio/aac": "aac",
  "audio/flac": "flac",
};

/** Writes server-generated bytes as a private upload owned by the user; returns its URL. */
export async function saveGeneratedFile(userId: string, data: Uint8Array, mediaType: string): Promise<string> {
  const ext = GENERATED_EXT[mediaType.split(";")[0].trim().toLowerCase()];
  if (!ext) throw new Error(`Unsupported generated file type: ${mediaType}`);
  const { uploadStorage } = await import("@/lib/storage");
  const name = newUploadName(ext, userId);
  await uploadStorage().put(name, data, mediaType);
  return `/uploads/${name}`;
}

const ownerTag = (userId: string) => userId.replace(/[^A-Za-z0-9]/g, "").slice(0, 40) || "anon";

/** "<owner>_<time>-<uuid>.<ext>": the owner prefix lets the server check access without a lookup. */
export function newUploadName(ext: string, userId: string): string {
  return `${ownerTag(userId)}_${Date.now()}-${randomUUID()}.${ext}`;
}

export function uploadNameForMime(mime: string, userId: string): string | null {
  const ext = EXT_BY_MIME[mime];
  return ext ? newUploadName(ext, userId) : null;
}

/** Returns `name` if it is a bare file name that can't escape the uploads dir, else throws. */
export function safeUploadName(name: string): string {
  if (!name || name.startsWith(".") || name !== path.basename(name) || name.includes("\\")) {
    throw new Error("Invalid upload path");
  }
  return name;
}

/** The file name of an "/uploads/<file>" URL, or throws if it could escape the uploads dir. */
export function uploadName(url: string): string {
  return safeUploadName(url.startsWith("/uploads/") ? url.slice("/uploads/".length) : "");
}

/** True when the file was uploaded by this user (new-style, owner-prefixed name). */
export function isOwnUpload(url: string, userId: string): boolean {
  try {
    return uploadName(url).startsWith(`${ownerTag(userId)}_`);
  } catch {
    return false;
  }
}

/** Maps a "/uploads/<file>" URL to its path on disk, rejecting anything that escapes the uploads dir. */
export function resolveUploadUrl(url: string): string {
  const name = uploadName(url);
  const current = path.join(UPLOAD_DIR, name);
  if (existsSync(current)) return current;
  const legacy = path.join(LEGACY_UPLOAD_DIR, name);
  return existsSync(legacy) ? legacy : current;
}
